#!/usr/bin/env python3
"""Refuse co-author and tool-attribution trailers in a PR's own commits (#628).

CONTRIBUTING.md ("Commit and PR conventions") forbids `Co-authored-by` and tool-attribution
trailers. The rule was prose only: the 2026-10-23 review (§5 Commit hygiene) found 12 of the
last 200 commits on main carrying them. This is the mechanical half.

It reads only the commits in BASE..HEAD — the PR's own — so history already on main never
fails a later PR. Every line of every message is read, not only git's trailer block:
`git interpret-trailers --parse` sees the final paragraph alone, and a tool's
"Generated with <tool>" footer usually sits in a paragraph of its own above that block.
Matching is case-insensitive. Flagged:

- co-author: a `Co-authored-by:` (or `Co-developed-by:`) line;
- tool-attribution: a `Generated-by:`, `Generated-with:`, `Assisted-by:` or
  `AI-assisted-by:` line, or a line opening "Generated with" / "Generated by" that names an
  AI tool (the default footer some coding agents append).

`Signed-off-by:` (DCO) is not attribution and passes; so does prose that merely names a
trailer mid-sentence.

    python3 scripts/check_trailers.py --base <sha> [--head <sha>] [--root DIR]

Exit 0: no forbidden line in the range (an empty range included). 1: at least one commit
carries one, printed as `<sha12> <rule>: <line>`. 2: could not run — git absent, or BASE or
HEAD does not resolve (a shallow checkout must not pass as clean).
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

EXIT_CLEAN, EXIT_FINDINGS, EXIT_CANNOT_RUN = 0, 1, 2

AI_TOOLS = (r"claude|copilot|chatgpt|gpt-?\d\w*|codex|cursor|gemini|aider|devin|windsurf"
            r"|openai|anthropic|llm|ai")

RULES = (
    ("co-author", re.compile(r"^\s*co-(authored|developed)-by\s*:", re.IGNORECASE)),
    ("tool-attribution",
     re.compile(r"^\s*(ai-)?(generated-(by|with)|assisted-by)\s*:", re.IGNORECASE)),
    ("tool-attribution",
     re.compile(rf"^\W*generated\s+(with|by)\b.*\b({AI_TOOLS})\b", re.IGNORECASE)),
)


def _git(root, *args):
    return subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True)


def _resolves(root, rev):
    return _git(root, "rev-parse", "--verify", "--quiet", f"{rev}^{{commit}}").returncode == 0


def commits(root, base, head):
    """[(sha, message)] for BASE..HEAD, newest first. Raises ValueError if either end is
    unresolvable and OSError if git is absent."""
    for name, rev in (("base", base), ("head", head)):
        if not _resolves(root, rev):
            raise ValueError(f"{name} {rev!r} does not resolve to a commit "
                             "(fetch full history: actions/checkout fetch-depth: 0)")
    proc = _git(root, "log", "--no-show-signature", "--no-color", "-z", "--format=%H%n%B",
                f"{base}..{head}")
    if proc.returncode != 0:
        raise ValueError(f"git log {base}..{head} failed: {proc.stderr.strip()}")
    out = []
    for record in proc.stdout.split("\0"):
        record = record.strip("\n")
        if record:
            sha, _, message = record.partition("\n")
            out.append((sha, message))
    return out


def _short(rev):
    return rev[:12] if re.fullmatch(r"[0-9a-f]{40}", rev) else rev


def findings(message):
    """[(rule, line)] for every forbidden line in one commit message."""
    hits = []
    for line in message.splitlines():
        for rule, pattern in RULES:
            if pattern.search(line):
                hits.append((rule, line.strip()))
                break
    return hits


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    ap.add_argument("--base", required=True, help="the PR's base commit (excluded)")
    ap.add_argument("--head", default="HEAD", help="the PR's head commit (default HEAD)")
    ap.add_argument("--root", default=str(ROOT), help="repository to read (default: this one)")
    args = ap.parse_args(argv)
    try:
        log = commits(args.root, args.base, args.head)
    except (OSError, ValueError) as e:
        print(f"check_trailers: cannot run: {e}", file=sys.stderr)
        return EXIT_CANNOT_RUN
    bad = 0
    for sha, message in log:
        for rule, line in findings(message):
            bad += 1
            print(f"{sha[:12]} {rule}: {line}")
    if bad:
        print(f"\n{bad} forbidden trailer line(s) in {_short(args.base)}..{_short(args.head)}. "
              "CONTRIBUTING.md forbids co-author and tool-attribution trailers: reword the "
              "commit(s) without them and force-push the branch with --force-with-lease.")
        return EXIT_FINDINGS
    print(f"no co-author or tool-attribution trailers in {len(log)} commit(s)")
    return EXIT_CLEAN


if __name__ == "__main__":
    sys.exit(main())
